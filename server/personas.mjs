export function conversationWithSpeakers(history, currentPet) {
  return history.map(message => {
    const pet = Object.hasOwn(PERSONAS, message.pet) ? message.pet : Object.keys(PERSONAS).find(id => PERSONAS[id].name === message.name);
    return {
      role: message.role,
      speaker: message.role === 'user' ? '用户' : PERSONAS[pet]?.name || '历史伙伴（身份未记录）',
      currentCompanion: message.role === 'assistant' && pet === currentPet,
      text: message.text,
    };
  });
}
